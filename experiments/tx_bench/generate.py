"""Precompute an experimental CC1101 OOK sideband; no RF is emitted here.

Original implementation. PHY mapping follows our synthetic decoder fixtures.
This is NOT evidence that a physical LoRa receiver accepts the waveform.
"""
from pathlib import Path
import hashlib
import hmac
import json
import struct
from cryptography.hazmat.primitives.ciphers import Cipher, algorithms, modes

BW, SF, RATE = 62500, 7, 1000000
PERIOD = (1 << SF) * RATE // BW
LOW = 10000
CENTER = 910525000
CARRIER = CENTER - BW // 2 - LOW
KEY = bytes.fromhex('8b3387e9c5cdea6ac9e5edbaa115cd72')


def frame():
    # Direct (not flood), empty path, Public channel text. Explicit test identity.
    text = b'Flipper bench: TEST 01'
    plain = struct.pack('<IB', 1791763200, 0) + text
    plain += bytes((-len(plain)) % 16)
    enc = Cipher(algorithms.AES(KEY), modes.ECB()).encryptor()
    cipher = enc.update(plain) + enc.finalize()
    return bytes([0x16, 0, hashlib.sha256(KEY).digest()[0]]) + hmac.digest(KEY, cipher, 'sha256')[:2] + cipher


def crc16(data):
    crc = 0
    for b in data:
        crc ^= b << 8
        for _ in range(8):
            crc = ((crc << 1) ^ (0x1021 if crc & 0x8000 else 0)) & 65535
    return crc


def block(nibbles, bits, cr, reduced=False):
    words = []
    for n in nibbles:
        d = [(n >> i) & 1 for i in range(4)]
        parity = [d[0]^d[1]^d[2]^d[3]] if cr == 1 else [
            d[0]^d[1]^d[2], d[1]^d[2]^d[3], d[0]^d[1]^d[3], d[0]^d[2]^d[3]]
        words.append(d + parity[:cr])
    result = []
    for i in range(4 + cr):
        gray = 0
        for j in range(bits):
            gray = gray * 2 + words[(i-j-1) % bits][i]
        value, shifted = gray, gray >> 1
        while shifted:
            value ^= shifted
            shifted >>= 1
        result.append((value * (4 if reduced else 1) + 1) % 128)
    return result


def symbols(data, cr):
    h = [len(data) >> 4, len(data) & 15, cr * 2 + 1]
    check = 0
    for masks in [(15,0,0), (8,14,1), (4,9,10), (2,5,7), (1,2,15)]:
        check = check * 2 + sum(bin(a & b).count('1') for a,b in zip(h,masks)) % 2
    w, encoded = 255, []
    for b in data:
        encoded.append(b ^ w)
        w = ((w << 1) | (((w >> 7) ^ (w >> 5) ^ (w >> 4) ^ (w >> 3)) & 1)) & 255
    crc = crc16(data[:-2]) ^ data[-1] ^ (data[-2] << 8)
    encoded += [crc & 255, crc >> 8]
    nibbles = [n for b in encoded for n in (b & 15, b >> 4)]
    syms = block(h + [check >> 4, check & 15], 5, 4, True)
    for i in range(0, len(nibbles), 7):
        row = nibbles[i:i+7]
        syms += block(row + [0] * (7-len(row)), 7, cr)
    return syms


def segments(cr=None):
    result = [(0, 1, PERIOD)] * 32
    if cr is not None:
        result += [(8, 1, PERIOD), (16, 1, PERIOD)]
        result += [(0, -1, PERIOD)] * 2 + [(0, -1, PERIOD//4)]
        result += [(s, 1, PERIOD) for s in symbols(frame(), cr)]
    return result


def waveform(parts):
    # Exact integration on each 1us interval: wraps lie on integer sample edges.
    # Preserve phase across wraps, symbols and the SFD; do not replay RX slices.
    phase = .25
    levels, frequencies = [], []
    for shift, direction, length in parts:
        for t in range(length):
            fraction = ((t + .5) / PERIOD + shift / 128) % 1
            f = LOW + BW * (fraction if direction > 0 else 1 - fraction)
            levels.append(phase < .5)
            frequencies.append(f)
            phase = (phase + f/RATE) % 1
    return levels, frequencies


def runs(levels):
    assert levels and levels[0]
    durations, last, count = [], levels[0], 0
    for level in levels:
        if level != last:
            durations.append(count)
            count, last = 0, level
        count += 1
    durations.append(count)
    return durations


def generate(destination):
    destination.mkdir(parents=True, exist_ok=True)
    header = ['/* Generated by generate.py; durations in microseconds, first level high. */',
              '#pragma once', '#include <stdint.h>',
              f'#define BENCH_CARRIER {CARRIER}U']
    metadata = dict(sample_rate=RATE, target_center=CENTER, carrier_requested=CARRIER,
                    bandwidth=BW, spreading_factor=SF, lower_sideband_center=CARRIER-(LOW+BW//2),
                    payload_hex=frame().hex(), hardware_validation="See README.md result record", waveforms=[])
    waves = [('Tone 41.25k', 'tone', [(0,0,0)]),
             ('MC preamble', 'preamble', segments()),
             ('MC packet CR5', 'packet5', segments(1)),
             ('MC packet CR8', 'packet8', segments(4))]
    for title, name, parts in waves:
        if name == 'tone':
            levels = [((.25 + i*41250/RATE) % 1) < .5 for i in range(65536)]
        else:
            levels, _ = waveform(parts)
        durations = runs(levels)
        if durations[-1] == 1:
            levels.append(levels[-1])
            durations[-1] = 2
        # Last short tail may be merged into the low trailer by the HAL; reject
        # all shortened runs rather than silently accepting HAL's 2us clamp.
        assert min(durations) >= 2 and max(durations) < 256
        header += [f'static const uint8_t {name}[] = {{']
        header += [','.join(map(str,durations[i:i+32]))+',' for i in range(0,len(durations),32)]
        header += ['};']
        metadata['waveforms'].append(dict(name=name,title=title,duration_us=len(levels),
                                         edges=len(durations),minimum_pulse_us=min(durations)))
    header += ['typedef struct { const char* name; const uint8_t* data; uint32_t count, duration_us; } BenchWave;',
               'static const BenchWave waves[] = {']
    for w in metadata['waveforms']:
        header.append('{"%s", %s, sizeof(%s), %d},' % (w['title'],w['name'],w['name'],w['duration_us']))
    header += ['};']
    (destination/'waveforms.h').write_text('\n'.join(header)+'\n')
    (destination/'waveforms.json').write_text(json.dumps(metadata,indent=2)+'\n')
    print(json.dumps(metadata,indent=2))


if __name__ == '__main__':
    generate(Path(__file__).resolve().parent)
